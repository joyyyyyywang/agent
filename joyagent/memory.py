"""Durable local memory with a recoverable JSONL mirror.

SQLite is authoritative. Every mutation and its audit event commit together;
``audit_outbox`` retains the events so a missing or damaged ``events.jsonl`` can
be rebuilt. Startup rebuilds the mirror atomically (linear in event history),
and successful writes append new events. An unavailable mirror never discards a
committed database write. Stable event IDs make replay identifiable. A POSIX
advisory file lock and shared delivery cursor coordinate multiple processes;
a store is also safe to share between threads. macOS and Linux are supported;
Windows needs a different file-lock backend and fails clearly on construction.

Search combines lexical overlap and hashed token-vector cosine similarity.
These are local, deterministic features, NOT learned semantic embeddings.
Search scans the durable memory table, so it is intended for personal memory
collections rather than a large document corpus.
Deleting a conversation purges its messages and audit events and rebuilds the
mirror. A content-free tombstone prevents that session ID from being reused.
This does not erase external backups or promise storage-media sanitization.
Only explicitly supplied messages and memories are recorded; configuration,
environment variables, and provider credentials are never inspected here.
"""

from __future__ import annotations

from collections import Counter
from contextlib import contextmanager
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
import re
import sqlite3
import stat
import tempfile
from threading import RLock
from typing import Any
import uuid
import warnings

try:
    import fcntl
except ImportError:  # pragma: no cover - this first version targets macOS/Linux.
    fcntl = None

from .types import Message


_CJK = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]+")
_NEW_CONVERSATION_TITLE = "新会话"
# Historical associations include retired Agents; the live catalog filters them.
_AGENT_BACKENDS = ("joyagent", "codex", "opencode", "pi", "deepseek")


def _conversation_stats(db: sqlite3.Connection, prefix: str) -> dict[str, Any]:
    if not isinstance(prefix, str) or len(prefix) > 256 or "\0" in prefix:
        raise ValueError("prefix must be a string of at most 256 characters without NUL")
    # One SQLite statement gives consistent totals and associations. Counts are
    # independent of the paginated conversation list and include archived chats.
    # A conversation used by two agents belongs to both backend counts; the
    # overall count remains distinct. Empty conversations belong to neither.
    rows = db.execute("""
        WITH selected AS (
            SELECT session_id, archived FROM conversations AS c
            WHERE substr(session_id, 1, ?)=? AND NOT EXISTS (
                SELECT 1 FROM deleted_conversations AS d WHERE d.session_id=c.session_id)
        ), usage AS (
            SELECT m.session_id, CASE WHEN json_valid(m.payload) THEN
                CASE WHEN json_type(m.payload)='object'
                     THEN COALESCE(json_extract(m.payload, '$.backend'), 'joyagent') END
                END AS backend
            FROM messages AS m JOIN selected AS c ON c.session_id=m.session_id
            WHERE m.role='assistant'
        )
        SELECT '__total__', COUNT(*) FROM selected
        UNION ALL SELECT '__archived__', COUNT(*) FROM selected WHERE archived=1
        UNION ALL SELECT backend, COUNT(DISTINCT session_id) FROM usage
            WHERE backend IN ('joyagent', 'codex', 'opencode', 'pi', 'deepseek') GROUP BY backend
    """, (len(prefix), prefix)).fetchall()
    values = dict(rows)
    return {"total": values["__total__"], "archived": values["__archived__"],
            "by_backend": {backend: values.get(backend, 0) for backend in _AGENT_BACKENDS}}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="microseconds")


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False)


def _tokens(text: str) -> list[str]:
    text = text.casefold()
    tokens = re.findall(r"[^\W_]+", _CJK.sub(" ", text), re.UNICODE)
    for run in _CJK.findall(text):
        tokens.extend(run[i : i + 2] for i in range(len(run) - 1))
        if len(run) == 1:
            tokens.append(run)
    return tokens


def _limit(value: int, maximum: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not 1 <= value <= maximum:
        raise ValueError(f"limit must be an integer between 1 and {maximum}")
    return value


def _conversation_title(content: str) -> str:
    # Collapse line breaks and terminal controls; titles are public text, never
    # generated by a model or derived from tool/protocol metadata.
    text = "".join(" " if char.isspace() or ord(char) < 32 or 127 <= ord(char) <= 159
                   else char for char in content)
    return " ".join(text.split())[:48] or _NEW_CONVERSATION_TITLE


def validate_conversation_title(title: str) -> str:
    if not isinstance(title, str):
        raise ValueError("会话名称必须是字符串")
    # Validate before trimming so a newline/control at either end is not hidden.
    if any(ord(char) < 32 or 127 <= ord(char) <= 159
           or char in "\u2028\u2029" or 0xD800 <= ord(char) <= 0xDFFF for char in title):
        raise ValueError("会话名称须为单行文本，不能包含控制字符")
    title = title.strip()
    if not 1 <= len(title) <= 80:
        raise ValueError("会话名称须为 1–80 个字符")
    return title


class MemoryStore:
    def __init__(self, data_dir: Path, *, vector_dimensions: int = 256):
        if fcntl is None:
            raise RuntimeError("MemoryStore requires POSIX file locking (macOS/Linux); Windows is not supported yet")
        if (isinstance(vector_dimensions, bool) or not isinstance(vector_dimensions, int)
                or not 16 <= vector_dimensions <= 4096):
            raise ValueError("vector_dimensions must be an integer between 16 and 4096")
        self.data_dir = Path(data_dir)
        self.data_dir.mkdir(parents=True, exist_ok=True)
        self.audit_path = self.data_dir / "events.jsonl"
        self._audit_lock_path = self.data_dir / ".events.lock"
        self._audit_cursor_path = self.data_dir / ".events.cursor.json"
        self.db_path = self.data_dir / "memory.sqlite3"
        self.vector_dimensions = vector_dimensions
        self._lock = RLock()
        self._closed = False
        self._audit_seq = 0
        self._audit_dirty = True
        self._db = sqlite3.connect(self.db_path, timeout=30, check_same_thread=False)
        try:
            self._initialize()
        except BaseException:
            self._db.close()
            self._closed = True
            raise

    def _initialize(self) -> None:
        self._db.row_factory = sqlite3.Row
        self._db.execute("PRAGMA journal_mode=WAL")
        self._db.execute("PRAGMA synchronous=FULL")
        self._db.execute("PRAGMA secure_delete=ON")
        self._db.executescript("""
            CREATE TABLE IF NOT EXISTS messages (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                session_id TEXT NOT NULL,
                role TEXT NOT NULL,
                payload TEXT NOT NULL,
                created_at TEXT NOT NULL
            );
            CREATE INDEX IF NOT EXISTS messages_session_id ON messages(session_id, id);
            CREATE TABLE IF NOT EXISTS conversations (
                session_id TEXT PRIMARY KEY,
                title TEXT NOT NULL,
                title_custom INTEGER NOT NULL DEFAULT 0 CHECK(title_custom IN (0, 1)),
                archived INTEGER NOT NULL DEFAULT 0 CHECK(archived IN (0, 1)),
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                message_count INTEGER NOT NULL DEFAULT 0 CHECK(message_count >= 0)
            );
            CREATE INDEX IF NOT EXISTS conversations_activity
                ON conversations(archived, updated_at DESC, session_id);
            CREATE TABLE IF NOT EXISTS deleted_conversations (
                session_id TEXT PRIMARY KEY,
                deleted_at TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS memories (
                key TEXT PRIMARY KEY,
                value TEXT NOT NULL,
                tokens TEXT NOT NULL,
                vector TEXT NOT NULL,
                vector_dimensions INTEGER NOT NULL,
                updated_at TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS audit_outbox (
                seq INTEGER PRIMARY KEY AUTOINCREMENT,
                event_id TEXT NOT NULL UNIQUE,
                payload TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS audit_state (
                singleton INTEGER PRIMARY KEY CHECK(singleton=1),
                generation INTEGER NOT NULL
            );
            INSERT OR IGNORE INTO audit_state(singleton, generation) VALUES (1, 0);
        """)
        with self._db:
            # Serialize startup migration with writers and other initializers.
            # Derived metadata needs no extra audit event: its original message
            # events remain unchanged and authoritative.
            self._db.execute("BEGIN IMMEDIATE")
            columns = {row["name"] for row in self._db.execute("PRAGMA table_info(conversations)")}
            if "title_custom" not in columns:
                self._db.execute("""
                    ALTER TABLE conversations ADD COLUMN
                    title_custom INTEGER NOT NULL DEFAULT 0 CHECK(title_custom IN (0, 1))
                """)
            for row in self._db.execute("""
                SELECT m.session_id, COUNT(*) AS message_count,
                       MIN(m.created_at) AS created_at, MAX(m.created_at) AS updated_at
                FROM messages AS m LEFT JOIN conversations AS c ON c.session_id=m.session_id
                WHERE c.session_id IS NULL AND NOT EXISTS (
                    SELECT 1 FROM deleted_conversations AS d WHERE d.session_id=m.session_id
                ) GROUP BY m.session_id
            """).fetchall():
                self._db.execute("""
                    INSERT INTO conversations(session_id, title, created_at, updated_at, message_count)
                    VALUES (?, ?, ?, ?, ?)
                """, (row["session_id"], self._first_user_title(row["session_id"]),
                      row["created_at"], row["updated_at"], row["message_count"]))
            for row in self._db.execute(
                "SELECT key, value FROM memories WHERE vector_dimensions != ?",
                (self.vector_dimensions,),
            ).fetchall():
                tokens = _tokens(row["key"] + " " + row["value"])
                self._db.execute(
                    """UPDATE memories SET tokens=?, vector=?, vector_dimensions=?
                       WHERE key=? AND value=? AND vector_dimensions != ?""",
                    (_json(tokens), _json(self._vector(tokens)), self.vector_dimensions,
                     row["key"], row["value"], self.vector_dimensions),
                )
        self._flush_audit()

    def _ensure_open(self) -> None:
        if self._closed:
            raise RuntimeError("memory store is closed")

    @staticmethod
    def _session(session_id: str) -> str:
        if not isinstance(session_id, str) or not session_id.strip() or len(session_id) > 256:
            raise ValueError("session_id must be a nonempty string of at most 256 characters")
        return session_id

    @staticmethod
    def _key(key: str) -> str:
        if not isinstance(key, str) or not key.strip() or len(key) > 128:
            raise ValueError("memory key must be a nonempty string of at most 128 characters")
        return key.strip()

    def _first_user_title(self, session_id: str) -> str:
        row = self._db.execute(
            "SELECT payload FROM messages WHERE session_id=? AND role='user' ORDER BY id LIMIT 1",
            (session_id,),
        ).fetchone()
        if row is None:
            return _NEW_CONVERSATION_TITLE
        payload = json.loads(row["payload"])
        content = payload.get("content", "")
        return _conversation_title(content) if isinstance(content, str) else _NEW_CONVERSATION_TITLE

    @staticmethod
    def _conversation(row: sqlite3.Row) -> dict[str, Any]:
        result = dict(row)
        result.pop("title_custom", None)
        result["archived"] = bool(result["archived"])
        return result

    def _reject_deleted(self, session_id: str) -> None:
        """Check while holding SQLite's writer lock, before accepting content."""
        if self._db.execute("SELECT 1 FROM deleted_conversations WHERE session_id=?", (session_id,)).fetchone():
            raise ValueError("conversation has been deleted")

    def _vector(self, tokens: list[str]) -> dict[str, float]:
        vector: dict[str, float] = {}
        for token, count in Counter(tokens).items():
            digest = hashlib.blake2b(token.encode("utf-8"), digest_size=9).digest()
            index = str(int.from_bytes(digest[:8], "big") % self.vector_dimensions)
            sign = 1 if digest[8] & 1 else -1
            vector[index] = vector.get(index, 0.0) + sign * (1 + math.log(count))
        length = math.sqrt(sum(weight * weight for weight in vector.values()))
        return {index: weight / length for index, weight in vector.items()} if length else {}

    def _event(self, kind: str, data: dict[str, Any]) -> None:
        """Called inside the same transaction as the recorded mutation."""
        event_id = uuid.uuid4().hex
        self._db.execute(
            "INSERT INTO audit_outbox(event_id, payload) VALUES (?, ?)",
            (event_id, _json({"event_id": event_id, "type": kind, "timestamp": _now(), **data})),
        )

    @contextmanager
    def _audit_file_lock(self):
        # Never unlink this lock file: every writer must lock the same inode.
        with self._audit_lock_path.open("a+b") as lock_file:
            fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX)
            try:
                yield
            finally:
                fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)

    def _audit_signature(self) -> dict[str, int]:
        stat = self.audit_path.stat()
        return {"device": stat.st_dev, "inode": stat.st_ino,
                "size": stat.st_size, "modified_ns": stat.st_mtime_ns}

    def _audit_generation(self) -> int:
        return self._db.execute("SELECT generation FROM audit_state WHERE singleton=1").fetchone()[0]

    def _read_audit_cursor(self) -> int | None:
        """Read under the file lock; a stale/missing cursor means rebuild."""
        try:
            state = json.loads(self._audit_cursor_path.read_text(encoding="utf-8"))
            if not isinstance(state, dict) or state.get("signature") != self._audit_signature():
                return None
            generation = state.get("generation")
            if type(generation) is not int or generation != self._audit_generation():
                return None
            sequence = state.get("sequence")
            if isinstance(sequence, bool) or not isinstance(sequence, int) or sequence < 0:
                return None
            if sequence and not self._db.execute(
                "SELECT 1 FROM audit_outbox WHERE seq=?", (sequence,),
            ).fetchone():
                return None
            return sequence
        except (OSError, ValueError, UnicodeError):
            return None

    def _write_audit_cursor(self, sequence: int) -> None:
        """Publish only after the mirror is fsynced, while holding the lock.

        A crash before cursor replacement leaves a stale file signature, forcing
        a full rebuild rather than duplicate delivery on the next operation.
        """
        temporary: str | None = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", dir=self.data_dir,
                prefix=".cursor-", suffix=".tmp", delete=False,
            ) as cursor:
                temporary = cursor.name
                cursor.write(_json({"sequence": sequence, "signature": self._audit_signature(),
                                    "generation": self._audit_generation()}))
                cursor.flush()
                os.fsync(cursor.fileno())
            os.replace(temporary, self._audit_cursor_path)
            temporary = None
        finally:
            if temporary is not None:
                try:
                    os.unlink(temporary)
                except OSError:
                    pass

    def _rebuild_audit(self) -> None:
        temporary: str | None = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", dir=self.data_dir,
                prefix=".events-", suffix=".tmp", delete=False,
            ) as mirror:
                temporary = mirror.name
                sequence = 0
                for row in self._db.execute("SELECT seq, payload FROM audit_outbox ORDER BY seq"):
                    mirror.write(row["payload"] + "\n")
                    sequence = row["seq"]
                mirror.flush()
                os.fsync(mirror.fileno())
            os.replace(temporary, self.audit_path)
            temporary = None
            self._write_audit_cursor(sequence)
            self._audit_seq = sequence
            self._audit_dirty = False
        finally:
            if temporary is not None:
                try:
                    os.unlink(temporary)
                except OSError:
                    pass

    def _flush_audit(self) -> None:
        try:
            with self._audit_file_lock():
                sequence = self._read_audit_cursor()
                if self._audit_dirty or sequence is None:
                    self._rebuild_audit()
                    return
                # A different process may have delivered events since our last
                # flush. Always use its persisted cursor, never a cached value.
                self._audit_seq = sequence
                rows = self._db.execute(
                    "SELECT seq, payload FROM audit_outbox WHERE seq > ? ORDER BY seq",
                    (sequence,),
                ).fetchall()
                if not rows:
                    return
                with self.audit_path.open("a", encoding="utf-8") as mirror:
                    for row in rows:
                        mirror.write(row["payload"] + "\n")
                    mirror.flush()
                    os.fsync(mirror.fileno())
                self._write_audit_cursor(rows[-1]["seq"])
                self._audit_seq = rows[-1]["seq"]
        except OSError as error:
            self._audit_dirty = True
            warnings.warn(
                f"JSONL mirror unavailable; committed events remain in SQLite and will be replayed: {error}",
                RuntimeWarning, stacklevel=2,
            )

    def append_message(self, session_id: str, message: Message) -> None:
        self.append_messages(session_id, [message])

    def append_messages(self, session_id: str, messages: list[Message]) -> None:
        """Append a complete tool exchange atomically when possible."""
        session_id = self._session(session_id)
        if len(messages) > 1000:
            raise ValueError("append at most 1000 messages per transaction")
        # Serialize before starting a transaction so malformed input cannot partly commit.
        prepared = []
        for message in messages:
            if not isinstance(message, Message) or message.role not in {"system", "user", "assistant", "tool"}:
                raise ValueError("messages must contain Message objects with a supported role")
            payload = message.to_dict()
            prepared.append((message.role, _json(payload), payload))
        with self._lock:
            self._ensure_open()
            with self._db:
                self._db.execute("BEGIN IMMEDIATE")
                self._reject_deleted(session_id)
                for role, serialized, payload in prepared:
                    timestamp = _now()
                    self._db.execute(
                        "INSERT INTO messages(session_id, role, payload, created_at) VALUES (?, ?, ?, ?)",
                        (session_id, role, serialized, timestamp),
                    )
                    self._event("message.appended", {"session_id": session_id, "message": payload})
                if prepared:
                    # The transaction holds SQLite's writer lock, so the deleted
                    # check, counts/title cannot race another process, and the
                    # message events cover this derived metadata in one commit.
                    existing = self._db.execute(
                        "SELECT title, title_custom FROM conversations WHERE session_id=?", (session_id,),
                    ).fetchone()
                    if existing is None:
                        aggregate = self._db.execute("""
                            SELECT MIN(created_at), MAX(created_at), COUNT(*)
                            FROM messages WHERE session_id=?
                        """, (session_id,)).fetchone()
                        self._db.execute("""
                            INSERT INTO conversations(session_id, title, created_at, updated_at, message_count)
                            VALUES (?, ?, ?, ?, ?)
                        """, (session_id, self._first_user_title(session_id), *aggregate))
                    else:
                        title = (self._first_user_title(session_id)
                                 if not existing["title_custom"] and existing["title"] == _NEW_CONVERSATION_TITLE
                                 else existing["title"])
                        self._db.execute("""
                            UPDATE conversations SET title=?, updated_at=?, message_count=message_count+?
                            WHERE session_id=?
                        """, (title, timestamp, len(prepared), session_id))
            self._flush_audit()

    def history(self, session_id: str, limit: int = 40) -> list[Message]:
        """Return whole recent user turns; ``limit`` is a message-count hint.

        A single latest turn may exceed the limit, because clipping a tool result
        away from its assistant tool call produces an invalid provider request.
        The caller should also bound individual turns and total prompt size.
        """
        session_id = self._session(session_id)
        limit = _limit(limit, 1000)
        with self._lock:
            self._ensure_open()
            rows = list(reversed(self._db.execute(
                "SELECT id, role, payload FROM messages WHERE session_id=? ORDER BY id DESC LIMIT ?",
                (session_id, limit + 1),
            ).fetchall()))
            if len(rows) > limit:
                rows = rows[-limit:]
                start = next((i for i, row in enumerate(rows) if row["role"] == "user"), None)
                if start is not None:
                    rows = rows[start:]
                else:
                    # The latest turn alone is larger than the hint. Keep it intact.
                    last_user = self._db.execute(
                        "SELECT MAX(id) FROM messages WHERE session_id=? AND role='user'",
                        (session_id,),
                    ).fetchone()[0]
                    rows = self._db.execute(
                        "SELECT id, role, payload FROM messages WHERE session_id=? AND id>=? ORDER BY id",
                        (session_id, last_user or 0),
                    ).fetchall()
            return [Message.from_dict(json.loads(row["payload"])) for row in rows]

    def remember(self, key: str, value: str) -> dict[str, Any]:
        key = self._key(key)
        if not isinstance(value, str) or not value.strip() or len(value) > 8000:
            raise ValueError("memory value must be a nonempty string of at most 8000 characters")
        tokens = _tokens(key + " " + value)
        result = {"key": key, "value": value, "updated_at": _now()}
        with self._lock:
            self._ensure_open()
            with self._db:
                self._db.execute(
                    """INSERT INTO memories(key, value, tokens, vector, vector_dimensions, updated_at)
                       VALUES (?, ?, ?, ?, ?, ?)
                       ON CONFLICT(key) DO UPDATE SET value=excluded.value, tokens=excluded.tokens,
                       vector=excluded.vector, vector_dimensions=excluded.vector_dimensions,
                       updated_at=excluded.updated_at""",
                    (key, value, _json(tokens), _json(self._vector(tokens)),
                     self.vector_dimensions, result["updated_at"]),
                )
                self._event("memory.remembered", {"memory": result})
            self._flush_audit()
        return result

    def forget(self, key: str) -> bool:
        key = self._key(key)
        with self._lock:
            self._ensure_open()
            with self._db:
                deleted = self._db.execute("DELETE FROM memories WHERE key=?", (key,)).rowcount > 0
                if deleted:
                    self._event("memory.forgotten", {"key": key})
            self._flush_audit()
            return deleted

    def search(self, query: str, limit: int = 5) -> list[dict[str, Any]]:
        limit = _limit(limit, 100)
        if not isinstance(query, str) or len(query) > 8000:
            raise ValueError("query must be a string of at most 8000 characters")
        tokens = _tokens(query)
        query_set = set(tokens)
        with self._lock:
            self._ensure_open()
            if not query_set:
                return []
            query_vector = self._vector(tokens)
            results = []
            for row in self._db.execute("SELECT * FROM memories"):
                memory_set = set(json.loads(row["tokens"]))
                overlap = len(query_set & memory_set)
                if not overlap:
                    # Hash collisions alone are not evidence of a useful match.
                    continue
                lexical = overlap / math.sqrt(len(query_set) * len(memory_set))
                # Another runtime can choose a different hashing dimension.
                # Do not compare vectors built in incompatible coordinate spaces.
                vector = (json.loads(row["vector"]) if row["vector_dimensions"] == self.vector_dimensions
                          else self._vector(json.loads(row["tokens"])))
                cosine = sum(weight * vector.get(index, 0.0) for index, weight in query_vector.items())
                results.append({
                    "key": row["key"], "value": row["value"],
                    "score": round(0.75 * lexical + 0.25 * max(0.0, cosine), 6),
                    "updated_at": row["updated_at"],
                })
            results.sort(key=lambda item: (item["score"], item["updated_at"], item["key"]), reverse=True)
            return results[:limit]

    def list_memories(self, limit: int = 20) -> list[dict[str, Any]]:
        limit = _limit(limit, 1000)
        with self._lock:
            self._ensure_open()
            return [dict(row) for row in self._db.execute(
                "SELECT key, value, updated_at FROM memories ORDER BY updated_at DESC, key LIMIT ?",
                (limit,),
            )]

    def list_sessions(self) -> list[dict[str, Any]]:
        """Return up to the 1000 most recently updated sessions."""
        with self._lock:
            self._ensure_open()
            return [dict(row) for row in self._db.execute(
                """SELECT session_id, COUNT(*) AS message_count, MAX(created_at) AS updated_at
                   FROM messages GROUP BY session_id ORDER BY updated_at DESC LIMIT 1000"""
            )]

    def conversation_stats(self, *, prefix: str = "web:") -> dict[str, Any]:
        """Read aggregate counts only; never return titles, prompts or IDs."""
        with self._lock:
            self._ensure_open()
            return _conversation_stats(self._db, prefix)

    @staticmethod
    def read_conversation_stats(data_dir: Path, *, prefix: str = "web:") -> dict[str, Any]:
        """Inspect an inactive tenant without initializing memory or its audit.

        The caller validates trusted ancestor directories. A missing database
        means this visitor has no saved conversations; errors are not zeroes.
        """
        if not isinstance(prefix, str) or len(prefix) > 256 or "\0" in prefix:
            raise ValueError("prefix must be a string of at most 256 characters without NUL")
        directory = Path(data_dir)
        try:
            info = directory.lstat()
        except FileNotFoundError:
            return {"total": 0, "archived": 0, "by_backend": {key: 0 for key in _AGENT_BACKENDS}}
        if (not stat.S_ISDIR(info.st_mode) or info.st_uid != os.geteuid() or info.st_mode & 0o022):
            raise ValueError("会话状态目录必须由服务用户管理且不可被其他用户修改")
        path = directory / "memory.sqlite3"
        try:
            info = path.lstat()
        except FileNotFoundError:
            return {"total": 0, "archived": 0, "by_backend": {key: 0 for key in _AGENT_BACKENDS}}
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid()
                or info.st_mode & 0o022 or info.st_nlink != 1):
            raise ValueError("会话数据库必须是服务用户管理的普通文件")
        # mode=ro includes committed WAL data; immutable=1 would miss live writes.
        db = sqlite3.connect(path.absolute().as_uri() + "?mode=ro", uri=True, timeout=1)
        try:
            db.execute("PRAGMA query_only=ON")
            return _conversation_stats(db, prefix)
        finally:
            db.close()

    def get_conversation(self, session_id: str) -> dict[str, Any] | None:
        session_id = self._session(session_id)
        with self._lock:
            self._ensure_open()
            row = self._db.execute("SELECT * FROM conversations WHERE session_id=?", (session_id,)).fetchone()
            return self._conversation(row) if row is not None else None

    def list_conversations(self, *, prefix: str = "web:", archived: bool = False,
                           limit: int = 1000) -> list[dict[str, Any]]:
        if not isinstance(prefix, str) or len(prefix) > 256 or "\0" in prefix:
            raise ValueError("prefix must be a string of at most 256 characters without NUL")
        if type(archived) is not bool:
            raise ValueError("archived must be a boolean")
        limit = _limit(limit, 1000)
        with self._lock:
            self._ensure_open()
            # Literal, case-sensitive prefix matching; %, _ and quotes are not
            # patterns. Filter before limiting so other channels cannot crowd
            # the requested namespace out of the result.
            return [self._conversation(row) for row in self._db.execute("""
                SELECT * FROM conversations
                WHERE substr(session_id, 1, ?)=? AND archived=?
                ORDER BY updated_at DESC, session_id LIMIT ?
            """, (len(prefix), prefix, int(archived), limit))]

    def create_conversation(self, session_id: str) -> dict[str, Any]:
        session_id = self._session(session_id)
        with self._lock:
            self._ensure_open()
            timestamp = _now()
            with self._db:
                self._db.execute("BEGIN IMMEDIATE")
                self._reject_deleted(session_id)
                inserted = self._db.execute("""
                    INSERT INTO conversations(session_id, title, created_at, updated_at)
                    VALUES (?, ?, ?, ?) ON CONFLICT(session_id) DO NOTHING
                """, (session_id, _NEW_CONVERSATION_TITLE, timestamp, timestamp)).rowcount
                if not inserted:
                    raise ValueError("conversation already exists")
                row = self._db.execute("SELECT * FROM conversations WHERE session_id=?", (session_id,)).fetchone()
                result = self._conversation(row)
                self._event("conversation.created", {"conversation": result})
            self._flush_audit()
            return result

    def is_conversation_deleted(self, session_id: str) -> bool:
        session_id = self._session(session_id)
        with self._lock:
            self._ensure_open()
            return self._db.execute(
                "SELECT 1 FROM deleted_conversations WHERE session_id=?", (session_id,),
            ).fetchone() is not None

    def delete_conversation(self, session_id: str) -> dict[str, Any]:
        """Purge session content; return only after replacing its audit mirror.

        A mirror failure propagates even though SQLite may have committed. The
        tombstone makes retry safe; the audit generation forces every other
        store to rebuild rather than append to the obsolete mirror. Writers
        release their SQLite transaction before taking the audit file lock.
        """
        session_id = self._session(session_id)
        with self._lock:
            self._ensure_open()
            with self._audit_file_lock():
                with self._db:
                    self._db.execute("BEGIN IMMEDIATE")
                    deleted = self._db.execute(
                        "SELECT 1 FROM deleted_conversations WHERE session_id=?", (session_id,),
                    ).fetchone()
                    if deleted is None:
                        existing = self._db.execute(
                            "SELECT 1 FROM conversations WHERE session_id=?", (session_id,),
                        ).fetchone()
                        if existing is None:
                            raise ValueError("conversation does not exist")
                        self._db.execute("INSERT INTO deleted_conversations(session_id, deleted_at) VALUES (?, ?)",
                                         (session_id, _now()))
                    # Purge again on retry as well, before restoring the mirror.
                    self._db.execute("DELETE FROM messages WHERE session_id=?", (session_id,))
                    self._db.execute("DELETE FROM conversations WHERE session_id=?", (session_id,))
                    self._db.execute("""
                        DELETE FROM audit_outbox
                        WHERE json_extract(payload, '$.session_id')=?
                           OR json_extract(payload, '$.conversation.session_id')=?
                    """, (session_id, session_id))
                    self._db.execute("UPDATE audit_state SET generation=generation+1 WHERE singleton=1")
                self._audit_dirty = True
                # Unlike ordinary writes, deletion must not suppress a mirror
                # error or report success while old content is still present.
                self._rebuild_audit()
            return {"session_id": session_id, "deleted": True}

    def rename_conversation(self, session_id: str, title: str) -> dict[str, Any]:
        """Persist a user-selected title without changing history or execution."""
        session_id = self._session(session_id)
        title = validate_conversation_title(title)
        with self._lock:
            self._ensure_open()
            with self._db:
                self._db.execute("BEGIN IMMEDIATE")
                self._reject_deleted(session_id)
                changed = self._db.execute("""
                    UPDATE conversations SET title=?, title_custom=1, updated_at=?
                    WHERE session_id=? AND (title<>? OR title_custom=0)
                """, (title, _now(), session_id, title)).rowcount
                row = self._db.execute("SELECT * FROM conversations WHERE session_id=?", (session_id,)).fetchone()
                if row is None:
                    raise ValueError("conversation does not exist")
                result = self._conversation(row)
                if changed:
                    self._event("conversation.renamed", {"conversation": result})
            self._flush_audit()
            return result

    def set_conversation_archived(self, session_id: str, archived: bool) -> dict[str, Any]:
        session_id = self._session(session_id)
        if type(archived) is not bool:
            raise ValueError("archived must be a boolean")
        with self._lock:
            self._ensure_open()
            with self._db:
                changed = self._db.execute("""
                    UPDATE conversations SET archived=?, updated_at=?
                    WHERE session_id=? AND archived<>?
                """, (int(archived), _now(), session_id, int(archived))).rowcount
                row = self._db.execute("SELECT * FROM conversations WHERE session_id=?", (session_id,)).fetchone()
                if row is None:
                    raise ValueError("conversation does not exist")
                result = self._conversation(row)
                if changed:
                    self._event("conversation.archived" if archived else "conversation.restored",
                                {"conversation": result})
            self._flush_audit()
            return result

    def close(self) -> None:
        with self._lock:
            if not self._closed:
                self._flush_audit()
                self._db.close()
                self._closed = True
